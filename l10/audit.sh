    echo
    echo "## RSS trend (first vs. last sample — rough leak signal)"
    echo '```'
    awk -F, 'NR==2{first=$2} END{if(NR>2) printf "first_rss_kb=%d last_rss_kb=%d delta_kb=%d\n", first, $2, $2-first}' \
      "$OUTDIR/profile_proc.csv"
    echo '```'
  fi

  crashcount=$(ls "$OUTDIR"/crash_*.log 2>/dev/null | wc -l)
  if (( crashcount > 0 )); then
    echo
    echo "## CRASH DETECTED — see crash_*.log and crash_*.core in $OUTDIR"
