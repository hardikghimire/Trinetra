# ===========================================================================
# 2. Background /proc profiler — runs concurrently with the gdb trace
# ===========================================================================
profile_loop() {
  local target_pid="$1"
  local proclog="$OUTDIR/profile_proc.csv"
  local cpulog="$OUTDIR/profile_percpu.csv"
  local btlog="$OUTDIR/profile_backtraces.log"
  local netlog="$OUTDIR/profile_net.csv"
  echo "timestamp,rss_kb,threads,fd_count,ctx_switches_voluntary,ctx_switches_nonvoluntary" > "$proclog"
  echo "timestamp,tid,cpu_pct" > "$cpulog"
  echo "timestamp,rx_bytes,tx_bytes" > "$netlog"

  declare -A prev_utime
  local i=0
  local interval=2
  local hz; hz="$(getconf CLK_TCK 2>/dev/null || echo 100)"

  while kill -0 "$target_pid" 2>/dev/null; do
    local t; t="$(date +%s.%N)"

    if [[ -r /proc/$target_pid/status ]]; then
      local rss nthreads fdc vol nonvol
      rss="$(awk '/^VmRSS:/{print $2}' /proc/$target_pid/status 2>/dev/null)"
      nthreads="$(awk '/^Threads:/{print $2}' /proc/$target_pid/status 2>/dev/null)"
      fdc="$(ls /proc/$target_pid/fd 2>/dev/null | wc -l)"
      vol="$(awk '/^voluntary_ctxt_switches/{print $2}' /proc/$target_pid/status 2>/dev/null)"
      nonvol="$(awk '/^nonvoluntary_ctxt_switches/{print $2}' /proc/$target_pid/status 2>/dev/null)"
      echo "${t},${rss:-0},${nthreads:-0},${fdc:-0},${vol:-0},${nonvol:-0}" >> "$proclog"
    fi

    if [[ -d /proc/$target_pid/task ]]; then
      for tdir in /proc/$target_pid/task/*/; do
        local tid; tid="$(basename "$tdir")"
        [[ -r "${tdir}stat" ]] || continue
        read -r -a fields < "${tdir}stat" 2>/dev/null || continue
        local total=$(( ${fields[13]:-0} + ${fields[14]:-0} ))
        if [[ -n "${prev_utime[$tid]:-}" ]]; then
          local delta=$(( total - prev_utime[$tid] ))
          local pct; pct="$(awk -v d="$delta" -v hz="$hz" -v iv="$interval" 'BEGIN{printf "%.1f", (d/hz)/iv*100}')"
          echo "${t},${tid},${pct}" >> "$cpulog"
        fi
        prev_utime[$tid]="$total"
      done
    fi

    # whole-machine interface throughput (best-effort signal, not per-process)
    if [[ -r /proc/net/dev ]]; then
      awk -v t="$t" '
        NR>2 && $1 !~ /lo:/ {
          gsub(":","",$1); rx+=$2; tx+=$10
        }
        END { printf "%s,%d,%d\n", t, rx, tx }
      ' /proc/net/dev >> "$netlog"
    fi

    if (( i % 3 == 0 )); then
      {
        echo "=== snapshot @ ${t} ==="
        timeout 5 gdb -q -batch -p "$target_pid" \
          -ex "set pagination off" -ex "thread apply all bt" 2>/dev/null
        echo
      } >> "$btlog"
    fi

    i=$((i+1))
    sleep "$interval"
  done
}

