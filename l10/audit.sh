def now_thread():
    try:
        t = gdb.selected_thread()
        return t.num if t else -1
    except Exception:
        return -1

def caller_backtrace(depth=6):
    bt = []
    try:
        fr = gdb.selected_frame()
    except Exception:
        return bt
    d = 0
    while fr and d < depth:
        fn = fr.function()
        bt.append(fn.name if fn else "??")
        fr = fr.older()
        d += 1
    return bt

# --- thread lifecycle (named entry points) ----------------------------------
class ThreadEntryBP(gdb.Breakpoint):
    def __init__(self, spec, label):
        super().__init__(spec, internal=False)
        self.label = label
    def stop(self):
        tn = now_thread()
        if tn not in STATE["threads_seen"]:
            STATE["threads_seen"][tn] = self.label
            log(f"[THREAD] gdb-thread={tn} entered {self.label} at {time.time():.3f}")
        return False

# --- thread PROVENANCE: who actually spawns OS threads -----------------------
# Answers "which threads exist and who created them" directly, instead of inferring
# it from which named functions happen to get hit.
class ThreadSpawnBP(gdb.Breakpoint):
    def stop(self):
        bt = caller_backtrace(8)
        entry = {"t": time.time(), "gdb_thread": now_thread(), "caller_stack": bt}
        STATE["thread_spawns"].append(entry)
        log(f"[SPAWN] pthread_create called from gdb-thread={now_thread()}, "
            f"call stack: {' <- '.join(bt)}")
        return False

# --- PacketBufferPool acquire/release balance -------------------------------
class PoolAcquireBP(gdb.Breakpoint):
    def stop(self):
        STATE["pool_acquire"][now_thread()] += 1
        return False

class PoolReleaseBP(gdb.Breakpoint):
    def stop(self):
        tn = now_thread()
        STATE["pool_release"][tn] += 1
        if STATE["pool_release"][tn] > STATE["pool_acquire"][tn]:
            log(f"[POOL] WARNING over-release on gdb-thread={tn}: "
                f"released={STATE['pool_release'][tn]} acquired={STATE['pool_acquire'][tn]} "
                f"(possible double-release/UAF of a pool buffer)")
        return False

# --- io_uring lifecycle + submit-to-completion stall detection ---------------
class UringSubmitBP(gdb.Breakpoint):
    def __init__(self, spec, name):
        super().__init__(spec, internal=False)
        self.name = name
    def stop(self):
        STATE["uring_calls"][self.name] += 1
        STATE["uring_last_submit_t"][now_thread()] = time.time()
        return False

class UringWaitBP(gdb.Breakpoint):
    def __init__(self, spec, name):
        super().__init__(spec, internal=False)
        self.name = name
    def stop(self):
        STATE["uring_calls"][self.name] += 1
        tn = now_thread()
        last = STATE["uring_last_submit_t"].get(tn)
        if last is not None:
            stall = time.time() - last
            if stall > STATE["uring_max_stall_s"]:
                STATE["uring_max_stall_s"] = stall
            if stall > 0.05:  # 50ms: worth knowing about on a scanner's hot path
                STATE["uring_stall_events"] += 1
                if STATE["uring_stall_events"] % 20 == 1:
                    log(f"[URING] submit->wait stall {stall*1000:.1f}ms on gdb-thread={tn} "
                        f"(x{STATE['uring_stall_events']} such stalls so far — kernel not "
                        f"draining the ring promptly, or the wait timeout itself is large)")
        return False

class UringSqFullBP(gdb.Breakpoint):
    def stop(self):
        STATE["uring_sq_full_events"] += 1
        if STATE["uring_sq_full_events"] % 50 == 1:
            log(f"[URING] submission queue exhausted x{STATE['uring_sq_full_events']} "
                f"(producing packets faster than the ring drains — consider raising "
                f"send_uring_depth or checking completion consumption)")
        return False

