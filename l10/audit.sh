#!/usr/bin/env bash
#
# shiv_audit.sh — one-shot, full-spectrum GDB audit for Shiv (raw-socket / io_uring scanner)
#
# No flags to choose. Give it the scan command, or a running PID, and it does everything
# at once, automatically, into one timestamped output directory:
#
#   - full gdb correctness instrumentation: thread lifecycle & provenance, PacketBufferPool
#     acquire/release balance, io_uring ring lifecycle + submit-to-completion stall detection,
#     global_raw_sockets/global_uring_rings/global_worker_threads + mutex activity, the
#     g_ports_in_retry_global underflow watch, the arp_handler.cpp SIOCSARP bug-area probe,
#     raw socket()/close() fd-leak accounting, and probe.cpp's malloc/calloc/realloc/free family
#   - live /proc profiling running CONCURRENTLY with the gdb trace (per-thread CPU%, RSS,
#     fd count, ctx switches, /proc/net/dev throughput, periodic backtrace snapshots)
#   - automatic crash forensics (full multi-thread backtrace, registers, faulting
#     instruction, memory map, core file) if it crashes — no separate step needed
#   - an automatic consolidated REPORT.md at the end, every time
#
# Usage:
#   ./shiv_audit.sh ./shiv -sS -Pn nmap.org          # launch & audit a fresh run
#   ./shiv_audit.sh --pid 12345                       # attach to & audit a running scan
#
