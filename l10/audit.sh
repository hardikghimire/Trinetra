# --- ARP / SIOCSARP (known dst-mac/src-mac bug area) -------------------------
class ArpSiocsarpBP(gdb.Breakpoint):
    def stop(self):
        f = gdb.selected_frame()
        try:
            s = f.read_var("s")
        except Exception:
            s = "?"
        bt = caller_backtrace(8)
        STATE["arp_siocsarp_calls"].append({"t": time.time(), "sockfd": str(s), "backtrace": bt})
        log(f"[ARP] SIOCSARP ioctl called, sockfd={s}, call stack: {' <- '.join(bt)}")
        if any("send" in fn.lower() and "arp" not in fn.lower() for fn in bt):
            log("[ARP] *** POSSIBLE VIOLATION: SIOCSARP reached from something named "
                "like a send-path function — verify scan.cpp send path is not involved ***")
        return False

# --- g_ports_in_retry_global underflow watch ---------------------------------
class RetryCounterCheckBP(gdb.Breakpoint):
    def stop(self):
        try:
            val = int(gdb.parse_and_eval("g_ports_in_retry_global._M_i"))
        except Exception:
            try:
                val = int(gdb.parse_and_eval("g_ports_in_retry_global"))
            except Exception:
                return False
        if val > (1 << 62):
            STATE["retry_counter_negative_hits"] += 1
            log(f"[RETRY] g_ports_in_retry_global underflowed (raw={val}) — "
                f"a fetch_sub ran without a matching fetch_add somewhere in scan.cpp")
        return False

# --- manual allocation tracking (probe.cpp) -----------------------------------
# NOTE ON ACCURACY: this uses gdb.FinishBreakpoint to capture malloc's return value.
# FinishBreakpoint is known to be unreliable in heavily multi-threaded programs — if a
# different thread stops gdb before the original call returns, the pending finish can
# get silently dropped. When that happens, a later free() on that pointer looks
# "untracked" even though it's legitimate. That's tracked separately below and reported
# as a single count, not raised as false double-free alarms per occurrence.
class MallocRetBP(gdb.FinishBreakpoint):
    def __init__(self, size, tag):
        super().__init__(gdb.newest_frame(), internal=False)
        self.size = size
        self.tag = tag
    def stop(self):
        try:
            ptr = int(self.return_value)
        except Exception:
            return False
        if ptr:
            STATE["alloc_live"][ptr] = self.size
            STATE["alloc_bytes_outstanding"] += self.size
            if self.size > 1024*1024:
                log(f"[ALLOC] large {self.tag} of {self.size} bytes -> {hex(ptr)}")
        return False

class MallocEntryBP(gdb.Breakpoint):
    def __init__(self, spec, tag):
        super().__init__(spec, internal=False)
        self.tag = tag
    def stop(self):
        STATE["alloc_calls"][self.tag] += 1
        try:
            frame = gdb.selected_frame()
            if self.tag == "calloc":
                nmemb = int(frame.read_var("nmemb"))
                size = int(frame.read_var("size"))
                size *= nmemb
            else:
                size = int(frame.read_var("size"))
            MallocRetBP(size, self.tag)
        except Exception:
            pass
        return False

class FreeBP(gdb.Breakpoint):
    def stop(self):
        STATE["alloc_calls"]["free"] += 1
        try:
            ptr = int(gdb.selected_frame().read_var("ptr"))
        except Exception:
            ptr = None
        if ptr and ptr in STATE["alloc_live"]:
            STATE["alloc_bytes_outstanding"] -= STATE["alloc_live"].pop(ptr)
        elif ptr:
            STATE["alloc_untracked_frees"] += 1
        return False

# --- crash forensics -----------------------------------------------------------
def on_stop(event):
    if isinstance(event, gdb.SignalEvent):
        sig = event.stop_signal
        if sig in ("SIGSEGV", "SIGABRT", "SIGBUS", "SIGFPE", "SIGILL"):
            STATE["crashes"] += 1
            log(f"[CRASH] signal {sig} received — dumping full forensic snapshot")
            try:
                gdb.execute(f"set logging file {LOGDIR}/crash_{STATE['crashes']}.log")
                gdb.execute("set logging enabled on")
                gdb.execute("info registers")
                gdb.execute("thread apply all bt full")
                gdb.execute("info threads")
                gdb.execute("x/16i \$pc")
                gdb.execute("info proc mappings")
                gdb.execute(f"generate-core-file {LOGDIR}/crash_{STATE['crashes']}.core")
                gdb.execute("set logging enabled off")
            except Exception as e:
                log(f"[CRASH] forensic dump partially failed: {e}")
            try:
                f = gdb.newest_frame()
                top = []
                for _ in range(10):
                    if not f: break
                    fn = f.function()
                    top.append(fn.name if fn else "??")
                    f = f.older()
                log(f"[CRASH] top of stack (thread {now_thread()}): {' <- '.join(top)}")
            except Exception:
                pass

gdb.events.stop.connect(on_stop)

def dump_summary():
    thread_provenance = [
        {"t": e["t"], "gdb_thread": e["gdb_thread"], "caller_stack": e["caller_stack"]}
        for e in STATE["thread_spawns"]
    ]
    summary = {
        "alloc_calls": dict(STATE["alloc_calls"]),
        "alloc_bytes_outstanding_at_exit": STATE["alloc_bytes_outstanding"],
        "alloc_ptrs_never_freed": len(STATE["alloc_live"]),
        "alloc_untracked_frees": STATE["alloc_untracked_frees"],
        "alloc_untracked_frees_note": (
            "Frees on pointers this session never saw allocated. Usually a gdb "
            "FinishBreakpoint tracking gap under thread concurrency, not a real bug -- "
            "cross-check against alloc_ptrs_never_freed (0 there means everything this "
            "session DID track was balanced)."
        ),
        "pool_acquire_by_thread": dict(STATE["pool_acquire"]),
        "pool_release_by_thread": dict(STATE["pool_release"]),
        "pool_imbalance": {
            str(k): STATE["pool_acquire"][k] - STATE["pool_release"].get(k, 0)
            for k in STATE["pool_acquire"]
        },
        "uring_calls": dict(STATE["uring_calls"]),
        "uring_sq_full_events": STATE["uring_sq_full_events"],
        "uring_stall_events_over_50ms": STATE["uring_stall_events"],
        "uring_max_stall_ms": round(STATE["uring_max_stall_s"] * 1000, 1),
        "threads_seen_named": {str(k): v for k, v in STATE["threads_seen"].items()},
        "thread_spawn_count": len(STATE["thread_spawns"]),
        "socket_opens": STATE["socket_opens"],
        "socket_closes": STATE["socket_closes"],
        "socket_fd_delta": STATE["socket_opens"] - STATE["socket_closes"],
        "arp_siocsarp_call_count": len(STATE["arp_siocsarp_calls"]),
        "retry_counter_underflow_hits": STATE["retry_counter_negative_hits"],
        "mutex_lock_events": STATE["mutex_lock_events"],
        "crashes": STATE["crashes"],
    }
    with open(os.path.join(LOGDIR, "audit_summary.json"), "w") as f:
        json.dump(summary, f, indent=2)
    with open(os.path.join(LOGDIR, "thread_provenance.json"), "w") as f:
        json.dump(thread_provenance, f, indent=2)
    log("[SUMMARY] wrote audit_summary.json and thread_provenance.json")
    for tid, acq in STATE["pool_acquire"].items():
        rel = STATE["pool_release"].get(tid, 0)
        if acq - rel != 0:
            log(f"[POOL] gdb-thread {tid}: acquire={acq} release={rel} "
                f"imbalance={acq-rel} (nonzero at exit -> leaked or over-released buffers)")
    if STATE["socket_opens"] != STATE["socket_closes"]:
        log(f"[SOCKET] fd delta at exit: opened={STATE['socket_opens']} "
            f"closed={STATE['socket_closes']} (nonzero -> likely fd leak on exit/error path)")

def on_exit(event):
    log(f"[EXIT] process exited, code={getattr(event,'exit_code','?')}")
    dump_summary()

gdb.events.exited.connect(on_exit)
end

