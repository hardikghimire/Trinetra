if [[ "$MODE" == "launch" ]]; then
  gdb -q -batch -x "$GDBFILE" --args "$BIN" $ARGS > "$OUTDIR/gdb_stdout.log" 2>&1 &
  GDB_BGPID=$!

  # Discover the inferior's real PID so the profiler can watch it (gdb is its direct parent).
  TARGET_PID=""
  for _ in $(seq 1 100); do
    TARGET_PID="$(pgrep -P "$GDB_BGPID" 2>/dev/null | head -1)"
    [[ -n "$TARGET_PID" ]] && break
    kill -0 "$GDB_BGPID" 2>/dev/null || break
    sleep 0.1
  done

  if [[ -n "$TARGET_PID" ]]; then
    echo "[*] Profiling live target pid $TARGET_PID alongside the trace."
    profile_loop "$TARGET_PID" &
    PROFILE_BGPID=$!
  else
    echo "[!] Could not discover the inferior's pid in time — trace will still run, but no profiler data."
    PROFILE_BGPID=""
  fi

  wait "$GDB_BGPID"
  [[ -n "$PROFILE_BGPID" ]] && kill "$PROFILE_BGPID" 2>/dev/null

else
  echo "[*] Attaching to PID $PID for up to ${ATTACH_DURATION}s (stops early if the process exits)."
  profile_loop "$PID" &
  PROFILE_BGPID=$!

  timeout "${ATTACH_DURATION}s" gdb -q -batch -x "$GDBFILE" -p "$PID" > "$OUTDIR/gdb_stdout.log" 2>&1
  kill "$PROFILE_BGPID" 2>/dev/null
fi

